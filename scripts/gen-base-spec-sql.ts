// Generates drizzle/migrations/0007_seed_unit_base_spec.sql from src/lib/baseSpec.ts.
// Run: bun scripts/gen-base-spec-sql.ts   (scripts/base-spec.test.ts asserts the file is in sync)
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BASE_SPEC } from '../src/lib/baseSpec';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const nullable = (s: string | null) => (s === null ? 'NULL' : q(s));

export function generateBaseSpecSql(): string {
  const tuples = BASE_SPEC.map(
    (r) =>
      `  (${q(r.unitTypeCode)}, ${q(r.section)}, ${q(r.location)}, ${q(r.label)}, ${nullable(r.defaultProduct)}, ${q(JSON.stringify(r.defaultColourOptions))}::jsonb, ${r.isIncluded})`,
  );
  return [
    '-- Phase 2: seed unit_base_spec (standard inclusions per logical unit type A-J).',
    '-- GENERATED by scripts/gen-base-spec-sql.ts from src/lib/baseSpec.ts; edit the constant and regenerate.',
    '-- Idempotent: the natural-key unique index plus ON CONFLICT DO NOTHING make re-runs a no-op.',
    'CREATE UNIQUE INDEX IF NOT EXISTS unit_base_spec_natural_key',
    '  ON public.unit_base_spec (unit_type_code, section, location, label);',
    '',
    'INSERT INTO public.unit_base_spec (unit_type_code, section, location, label, default_product, default_colour_options, is_included) VALUES',
    tuples.join(',\n'),
    'ON CONFLICT (unit_type_code, section, location, label) DO NOTHING;',
    '',
  ].join('\n');
}

if (import.meta.main) {
  const out = join(import.meta.dir, '../drizzle/migrations/0007_seed_unit_base_spec.sql');
  writeFileSync(out, generateBaseSpecSql());
  console.log(`wrote ${out} (${BASE_SPEC.length} rows)`);
}
