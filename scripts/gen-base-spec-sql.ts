// Generates, from src/lib/baseSpec.ts:
//   drizzle/migrations/0007_seed_unit_base_spec.sql   (the unit_base_spec seed)
//   supabase/functions/_shared/baseSpecData.ts         (the edge mirror; edge functions cannot import src/)
// Run: bun scripts/gen-base-spec-sql.ts   (scripts/base-spec.test.ts and scripts/wizard-lines.test.ts assert both are in sync)
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BASE_SPEC } from '../src/lib/baseSpec';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const nullable = (s: string | null) => (s === null ? 'NULL' : q(s));

export function generateBaseSpecSql(): string {
  const tuples = BASE_SPEC.map(
    (r) =>
      `  (${q(r.unitTypeCode)}, ${q(r.section)}, ${q(r.location)}, ${q(r.label)}, ${nullable(r.defaultProduct)}, ${q(JSON.stringify(r.defaultColourOptions))}::jsonb, ${r.isIncluded})`,
  );
  return [
    '-- Phase 2: seed unit_base_spec (standard inclusions per logical unit type A-J).',
    '-- GENERATED by scripts/gen-base-spec-sql.ts from src/lib/baseSpec.ts; edit the constant and regenerate.',
    '-- Idempotent: the natural-key unique index plus ON CONFLICT DO NOTHING make re-runs a no-op.',
    'CREATE UNIQUE INDEX IF NOT EXISTS unit_base_spec_natural_key',
    '  ON public.unit_base_spec (unit_type_code, section, location, label);',
    '',
    'INSERT INTO public.unit_base_spec (unit_type_code, section, location, label, default_product, default_colour_options, is_included) VALUES',
    tuples.join(',\n'),
    'ON CONFLICT (unit_type_code, section, location, label) DO NOTHING;',
    '',
  ].join('\n');
}

/** The edge mirror of BASE_SPEC (byte-for-byte output of this function; never edit the file by hand). */
export function generateBaseSpecTs(): string {
  const rows = BASE_SPEC.map((r) => `  ${JSON.stringify({
    unitTypeCode: r.unitTypeCode, section: r.section, location: r.location, label: r.label,
    defaultProduct: r.defaultProduct, defaultColourOptions: r.defaultColourOptions, isIncluded: r.isIncluded,
  })},`);
  return [
    '// GENERATED by scripts/gen-base-spec-sql.ts from src/lib/baseSpec.ts; edit the constant and regenerate.',
    '// Edge mirror of BASE_SPEC (edge functions cannot import src/). No prices.',
    "import { normalizeUnitTypeCode, type QuoteBaseSpecRow } from './quoteLines.ts';",
    '',
    'export interface BaseSpecDataRow extends QuoteBaseSpecRow { unitTypeCode: string; defaultColourOptions: string[] }',
    '',
    'export const BASE_SPEC_DATA: readonly BaseSpecDataRow[] = [',
    ...rows,
    '];',
    '',
    '/** Same contract as baseSpecFor in src/lib/baseSpec.ts: G-1/G-2 and labels resolve to the logical type; unknown → []. */',
    'export function baseSpecForCode(unitTypeCode: string | null | undefined): BaseSpecDataRow[] {',
    '  const normalized = normalizeUnitTypeCode(unitTypeCode ?? null);',
    '  if (!normalized) return [];',
    "  const logical = normalized.replace(/-[12]$/, '');",
    '  return BASE_SPEC_DATA.filter((r) => r.unitTypeCode === logical).map((r) => ({ ...r, defaultColourOptions: [...r.defaultColourOptions] }));',
    '}',
    '',
  ].join('\n');
}

if (import.meta.main) {
  const out = join(import.meta.dir, '../drizzle/migrations/0007_seed_unit_base_spec.sql');
  writeFileSync(out, generateBaseSpecSql());
  console.log(`wrote ${out} (${BASE_SPEC.length} rows)`);
  const ts = join(import.meta.dir, '../supabase/functions/_shared/baseSpecData.ts');
  writeFileSync(ts, generateBaseSpecTs());
  console.log(`wrote ${ts}`);
}
