// Server-side line regeneration for a wizard submission (Phase 2 Task 9). send-selections-email calls this after the
// `buyer_selections` insert with the SAVED row, the client-sent `windows` (validated here; locations only) and
// loadServerPricing's result. Client-sent lines/amounts are never trusted. Pure: the caller does the insert.
import { generateQuoteLines, sumQuoteLines, type QuoteLine, type QuotePricing } from './quoteLines.ts';
import { generateInputFromRowCore, type BuyerSelectionsRowLike } from './quoteSelectionsFromRow.ts';
import { baseSpecForCode } from './baseSpecData.ts';
import { validateWizardWindows } from './wizardWindows.ts';
import { pricingUnavailableReason } from './loadServerPricing.ts';

/** One `quote_lines` insert row (`counts_in_total` is generated by the DB; `id` defaults). */
export type WizardLineInsert = Omit<QuoteLine, 'id'> & { submission_id: string; source: 'wizard'; created_by: null };

export interface WizardSubmissionLines {
  lines: QuoteLine[];
  inserts: WizardLineInsert[];
  /** Set when the client `windows` list was rejected (lines then use generic window locations). */
  windowsRejected: string | null;
  subtotal: number;
}

export function wizardSubmissionLines(savedRow: BuyerSelectionsRowLike, rawWindows: unknown, pricing: QuotePricing): WizardSubmissionLines {
  const v = validateWizardWindows(rawWindows);
  const submissionId = String(savedRow.id ?? '');
  const lines = generateQuoteLines(generateInputFromRowCore(savedRow, pricing, baseSpecForCode(savedRow.unit_type), {
    source: 'wizard', windows: v.ok ? v.windows : null, submissionId: submissionId || undefined,
  }));
  const inserts = lines.map((l) => {
    const { id: _id, ...rest } = l;
    return { ...rest, submission_id: submissionId, source: 'wizard' as const, created_by: null };
  });
  return { lines, inserts, windowsRejected: v.ok ? null : v.reason, subtotal: sumQuoteLines(lines, pricing.gstRate).subtotal };
}

/** The single parity log line: client subtotal (request body) vs the server's sum. Never blocks. */
export function subtotalParityLog(submissionId: string, clientSubtotal: unknown, serverSubtotal: number): string {
  const c = Number(clientSubtotal);
  if (clientSubtotal === undefined || clientSubtotal === null || clientSubtotal === '' || !Number.isFinite(c)) {
    return `[quote_lines] parity submission=${submissionId} client_subtotal=missing server_subtotal=${serverSubtotal.toFixed(2)}`;
  }
  const match = c.toFixed(2) === serverSubtotal.toFixed(2);
  return `[quote_lines] parity submission=${submissionId} client_subtotal=${c.toFixed(2)} server_subtotal=${serverSubtotal.toFixed(2)} ${match ? 'match' : 'MISMATCH'}`;
}

export type WriteWizardLinesResult =
  | { status: 'written'; count: number }
  | { status: 'skipped'; reason: string }
  | { status: 'failed'; error: string };

/**
 * The submit path's whole quote_lines step. Never throws: the submission row already exists, so every outcome is
 * logged and the caller carries on to the emails. With pricing unavailable no insert is attempted (lines priced
 * from empty tables would be a wrong permanent record); the backfill can write them later, and it skips submissions
 * that already have lines.
 */
export async function writeWizardLines(args: {
  savedRow: BuyerSelectionsRowLike;
  rawWindows: unknown;
  rawSubtotal: unknown;
  pricing: QuotePricing & { config: Record<string, number>; materials: Record<string, number> };
  insertRows: (rows: WizardLineInsert[]) => Promise<{ error: string | null }>;
  log?: { info: (m: string) => void; warn: (m: string) => void; error: (m: string) => void };
}): Promise<WriteWizardLinesResult> {
  const log = args.log ?? { info: console.log, warn: console.warn, error: console.error };
  const id = String(args.savedRow?.id ?? '');
  try {
    const unavailable = pricingUnavailableReason(args.pricing);
    if (unavailable) {
      log.warn(`[quote_lines] lines skipped: pricing unavailable (${unavailable}) submission=${id}`);
      return { status: 'skipped', reason: `pricing unavailable (${unavailable})` };
    }
    const wl = wizardSubmissionLines(args.savedRow, args.rawWindows, args.pricing);
    if (wl.windowsRejected) log.warn(`[quote_lines] windows list ignored for ${id} (${wl.windowsRejected}); generic window locations used`);
    log.info(subtotalParityLog(id, args.rawSubtotal, wl.subtotal));
    const { error } = await args.insertRows(wl.inserts);
    if (error) {
      log.error(`[quote_lines] insert failed for ${id} (submission saved; lines missing): ${error}`);
      return { status: 'failed', error };
    }
    log.info(`[quote_lines] wrote ${wl.inserts.length} lines for ${id}`);
    return { status: 'written', count: wl.inserts.length };
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    log.error(`[quote_lines] generation failed for ${id} (submission saved; lines missing): ${msg}`);
    return { status: 'failed', error: msg };
  }
}
